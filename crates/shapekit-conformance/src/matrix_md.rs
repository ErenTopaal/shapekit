//! `MATRIX.md`: the divergence matrix for people and for the CI job summary.

use std::fmt::Write as _;

use crate::compare::ResultClass;
use crate::runner::{EntryClass, Matrix};

const ENTRY_ORDER: [EntryClass; 7] = [
    EntryClass::Pass,
    EntryClass::PassSomeUnsupported,
    EntryClass::Reference,
    EntryClass::DivergesFromNetwork,
    EntryClass::DivergesFromPeers,
    EntryClass::Unsupported,
    EntryClass::Error,
];

const ORDER: [ResultClass; 6] = [
    ResultClass::Pass,
    ResultClass::Reference,
    ResultClass::DivergesFromNetwork,
    ResultClass::DivergesFromPeers,
    ResultClass::Unsupported,
    ResultClass::Error,
];

fn cell_text(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

pub fn render(m: &Matrix) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# SDK divergence matrix\n");
    let _ = writeln!(
        out,
        "Corpus {}, {} entries, decode depth {} ({} for LedgerCloseMeta). Generated by `shapekit conformance run`.\n",
        m.corpus_version,
        m.entries.len(),
        m.decode_depth,
        m.ledger_decode_depth
    );

    let _ = writeln!(out, "## Testees\n");
    let _ = writeln!(
        out,
        "| testee | package | components | decode limits | ops | role |"
    );
    let _ = writeln!(out, "|---|---|---|---|---|---|");
    for t in &m.testees {
        let components: Vec<String> = t
            .components
            .iter()
            .map(|(k, v)| format!("{k} {v}"))
            .collect();
        let _ = writeln!(
            out,
            "| {} | {} {} | {} | {} | {} | {} |",
            t.key,
            t.package,
            t.version,
            cell_text(&components.join(", ")),
            t.decode_limits,
            t.ops.len(),
            t.reference_for
                .as_deref()
                .map(|r| format!("reference for {r}"))
                .unwrap_or_default()
        );
    }
    if let Some(r) = m.testees.iter().find(|t| t.reference_for.is_some()) {
        let _ = writeln!(
            out,
            "\n{} is the reference: every `expected_json` in the corpus is stellar-xdr {}'s own XDR-JSON rendering, so its `decode_json` and `encode_json` checks that agree with it are counted as `reference`, not as `pass`. They are that library agreeing with itself, not independent evidence; `shapekit conformance crosscheck` compares `expected_json` with the other SDKs' decoders instead. A reference check that disagrees is still a failure. An entry whose other checks pass is counted under `reference` in the entry summary and passes in the known-failures verdict.",
            r.key, m.generator_stellar_xdr
        );
    }

    let _ = writeln!(out, "\n## Summary (entries)\n");
    let mut entry_header = String::from("| testee |");
    let mut entry_rule = String::from("|---|");
    for c in ENTRY_ORDER {
        let _ = write!(entry_header, " {} |", c.label());
        entry_rule.push_str("---|");
    }
    let _ = writeln!(out, "{entry_header}\n{entry_rule}");
    for t in &m.testees {
        let counts = m.entry_summary.get(&t.key);
        let mut line = format!("| {} |", t.key);
        for c in ENTRY_ORDER {
            let n = counts.and_then(|x| x.get(&c)).copied().unwrap_or(0);
            let _ = write!(line, " {n} |");
        }
        let _ = writeln!(out, "{line}");
    }

    let _ = writeln!(
        out,
        "\nAn entry counts as its worst check. An entry whose checks all pass apart from ops the SDK does not implement (go has no `encode_json`) is `pass (some checks unsupported)`; `unsupported` is an entry none of whose checks ran. The check and per-op tables below count every check on its own.\n"
    );
    let mut header = String::from("| testee |");
    let mut rule = String::from("|---|");
    for r in ORDER {
        let _ = write!(header, " {r} |");
        rule.push_str("---|");
    }
    let _ = writeln!(out, "## Summary (checks)\n");
    let _ = writeln!(out, "{header}\n{rule}");
    for t in &m.testees {
        let totals = m.check_summary.get(&t.key);
        let mut line = format!("| {} |", t.key);
        for r in ORDER {
            let n = totals.and_then(|c| c.get(&r)).copied().unwrap_or(0);
            let _ = write!(line, " {n} |");
        }
        let _ = writeln!(out, "{line}");
    }

    let _ = writeln!(out, "\n## Summary (checks per op)\n");
    let mut op_header = String::from("| testee | op |");
    let mut op_rule = String::from("|---|---|");
    for r in ORDER {
        let _ = write!(op_header, " {r} |");
        op_rule.push_str("---|");
    }
    let _ = writeln!(out, "{op_header}\n{op_rule}");
    for t in &m.testees {
        for (op, counts) in m.op_summary.get(&t.key).into_iter().flatten() {
            let mut line = format!("| {} | {op} |", t.key);
            for r in ORDER {
                let _ = write!(line, " {} |", counts.get(&r).copied().unwrap_or(0));
            }
            let _ = writeln!(out, "{line}");
        }
    }

    let not_pass: Vec<_> = m
        .entries
        .iter()
        .filter(|e| e.cells.values().any(|c| c.result != ResultClass::Pass))
        .collect();
    let _ = writeln!(out, "\n## Entries that do not pass everywhere\n");
    if not_pass.is_empty() {
        let _ = writeln!(out, "None.");
    } else {
        let mut header = String::from("| entry |");
        let mut rule = String::from("|---|");
        for t in &m.testees {
            let _ = write!(header, " {} |", t.key);
            rule.push_str("---|");
        }
        let _ = writeln!(out, "{header}\n{rule}");
        for e in &not_pass {
            let mut line = format!("| `{}` |", e.id);
            for t in &m.testees {
                let text = match e.cells.get(&t.key) {
                    Some(c) => match &c.known_issue {
                        Some(issue) => format!("{} (known: {})", c.result, cell_text(issue)),
                        None => c.result.to_string(),
                    },
                    None => "not run".into(),
                };
                let _ = write!(line, " {text} |");
            }
            let _ = writeln!(out, "{line}");
        }

        let _ = writeln!(out, "\n## Details\n");
        for e in &not_pass {
            let _ = writeln!(out, "### `{}`\n", e.id);
            for (key, c) in &e.cells {
                for ch in c
                    .checks
                    .iter()
                    .filter(|ch| ch.result != ResultClass::Unsupported)
                {
                    let _ = writeln!(
                        out,
                        "- {key} `{}`: {}{}",
                        ch.check,
                        ch.outcome(),
                        ch.detail
                            .as_deref()
                            .map(|d| format!(", {}", cell_text(d)))
                            .unwrap_or_default()
                    );
                }
                let unsupported: Vec<&str> = c
                    .checks
                    .iter()
                    .filter(|ch| ch.result == ResultClass::Unsupported)
                    .map(|ch| ch.op.as_str())
                    .collect();
                if !unsupported.is_empty() {
                    let mut ops: Vec<&str> = unsupported.clone();
                    ops.sort_unstable();
                    ops.dedup();
                    let _ = writeln!(
                        out,
                        "- {key}: {} checks unsupported ({})",
                        unsupported.len(),
                        ops.join(", ")
                    );
                }
            }
            let _ = writeln!(out);
        }
    }

    // implementation-defined entries pass on any answer that is not a crash, so their answers
    // are listed here rather than among the failures
    let mut defined = String::new();
    for e in &m.entries {
        let mut lines = Vec::new();
        for (key, c) in &e.cells {
            for ch in c.checks.iter().filter(|ch| {
                ch.result == ResultClass::Pass
                    && ch
                        .detail
                        .as_deref()
                        .is_some_and(|d| d.starts_with("implementation-defined"))
            }) {
                lines.push(format!(
                    "- {key} `{}`: {}",
                    ch.check,
                    cell_text(&ch.actual.to_string())
                ));
            }
        }
        if !lines.is_empty() {
            let _ = writeln!(defined, "### `{}`\n", e.id);
            for l in lines {
                let _ = writeln!(defined, "{l}");
            }
            let _ = writeln!(defined);
        }
    }
    if !defined.is_empty() {
        let _ = writeln!(
            out,
            "\n## Implementation-defined answers\n\nNo answer is required on these entries, so each answer that is not a crash passes; this is what each SDK answered.\n"
        );
        out.push_str(&defined);
    }

    if !m.known_failure_problems.is_empty() {
        let _ = writeln!(out, "\n## Known-failures problems (the run fails)\n");
        for p in &m.known_failure_problems {
            let _ = writeln!(out, "- {}", cell_text(p));
        }
    }
    out
}
