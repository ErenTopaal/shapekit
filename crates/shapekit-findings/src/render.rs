//! `FINDINGS.md` from a collection.

use std::fmt::Write;

use crate::collect::{Collection, FindingRecord};

/// `../` once per component of `out`, the directory FINDINGS.md is written to relative to the
/// repository root, so a draft path relative to the root resolves from the file.
pub fn root_prefix(out: &std::path::Path) -> String {
    out.components()
        .filter(|c| matches!(c, std::path::Component::Normal(_)))
        .map(|_| "../")
        .collect()
}

fn link_or_decision(f: &FindingRecord, up: &str) -> String {
    match (&f.link, &f.reference, &f.reason) {
        (Some(l), _, _) => format!("[{}]({l})", short(l)),
        (_, Some(r), _) => format!("private: {r}"),
        (_, _, Some(r)) => r.clone(),
        _ => f
            .draft
            .as_ref()
            .map(|d| format!("not filed, draft [{d}]({up}{d})"))
            .unwrap_or_else(|| "not filed".into()),
    }
}

/// `owner/repo#n` for a GitHub issue or pull request link.
fn short(link: &str) -> String {
    let rest = link.trim_start_matches("https://github.com/");
    let parts: Vec<&str> = rest.split('/').collect();
    match parts[..] {
        [owner, repo, "issues" | "pull", n, ..] => format!("{owner}/{repo}#{n}"),
        _ => link.to_owned(),
    }
}

/// The markdown of `c`; `up` leads from the file's directory to the repository root
/// ([`root_prefix`]).
pub fn markdown(c: &Collection, up: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# Findings\n\nGenerated by `shapekit findings collect` from the runs listed under Inputs; `shapekit findings check` fails while any failure has no finding or any finding has no upstream link or recorded decision. Triage and statuses live in `findings/triage.toml`.\n"
    );
    // `failures` counts every failure, including the unmapped and the held ones
    let covered = c
        .summary
        .failures
        .saturating_sub(c.summary.unmapped + c.summary.held);
    let _ = writeln!(
        s,
        "{} failures: {} findings cover {covered}{}; {} unmapped.\n",
        c.summary.failures,
        c.summary.findings,
        if c.summary.held == 0 {
            String::new()
        } else {
            format!(", candidate findings hold {}", c.summary.held)
        },
        c.summary.unmapped,
    );
    let severities = [
        "halt",
        "data-loss",
        "wrong-data",
        "divergence",
        "robustness",
    ];
    let _ = writeln!(
        s,
        "| component | {} | total |\n|---|{}---|",
        severities.join(" | "),
        "---|".repeat(severities.len())
    );
    for (comp, by) in &c.summary.by_component {
        let cells: Vec<String> = severities
            .iter()
            .map(|sv| by.get(*sv).map_or(String::new(), |n| n.to_string()))
            .collect();
        let _ = writeln!(
            s,
            "| {comp} | {} | {} |",
            cells.join(" | "),
            by.values().sum::<usize>()
        );
    }
    let status: Vec<String> = c
        .summary
        .by_status
        .iter()
        .map(|(k, v)| format!("{k} {v}"))
        .collect();
    let _ = writeln!(s, "\nBy status: {}.\n", status.join(", "));

    let _ = writeln!(
        s,
        "| id | component | severity | CAPs | minimal entry | status | link or decision |\n|---|---|---|---|---|---|---|"
    );
    for f in &c.findings {
        let _ = writeln!(
            s,
            "| [{}](#{}) | {} | {} | {} | {} | {} | {} |",
            f.id,
            f.id.to_lowercase(),
            f.component,
            f.severity.name(),
            f.caps.join(", "),
            f.minimal_entry
                .as_deref()
                .map(|e| format!("`{e}`"))
                .unwrap_or_default(),
            f.status.name(),
            link_or_decision(f, up)
        );
    }
    for f in &c.findings {
        let _ = writeln!(s, "\n## {}\n\n{}\n", f.id, f.title);
        let _ = writeln!(s, "{}\n", f.cause);
        let _ = writeln!(
            s,
            "- component: {}\n- severity: {}\n- CAPs: {}\n- status: {} ({})",
            f.component,
            f.severity.name(),
            if f.caps.is_empty() {
                "none".into()
            } else {
                f.caps.join(", ")
            },
            f.status.name(),
            link_or_decision(f, up)
        );
        if let Some(e) = &f.minimal_entry {
            let _ = writeln!(s, "- minimal entry: `{e}`");
        }
        if let Some(r) = &f.reproduce {
            let _ = writeln!(s, "- reproduce: `{r}`");
        }
        if let Some(r) = &f.recipe {
            let _ = writeln!(s, "- recipe: `{r}`");
        }
        for a in &f.affected {
            let _ = writeln!(
                s,
                "- affected {}: fails on {} ({} of {} tested){}",
                a.on,
                a.failing.join(", "),
                a.failing.len(),
                a.tested.len(),
                a.passes_from
                    .as_deref()
                    .map(|v| format!(", passes from {v}"))
                    .unwrap_or_default()
            );
        }
        if !f.other_sdks.is_empty() {
            let _ = writeln!(
                s,
                "- other SDKs failing the same entries: {}",
                f.other_sdks.join(", ")
            );
        }
        if !f.siblings.is_empty() {
            let _ = writeln!(
                s,
                "- siblings: {}",
                f.siblings
                    .iter()
                    .map(|x| format!("[{x}](#{})", x.to_lowercase()))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        if !f.related.is_empty() {
            let _ = writeln!(
                s,
                "- related upstream: {}",
                f.related
                    .iter()
                    .map(|l| format!("[{}]({l})", short(l)))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        let answers = f
            .occurrences
            .iter()
            .filter(|o| o.source == "answer")
            .count();
        let _ = writeln!(
            s,
            "- observed: {} failure(s){} on {} entr{}",
            f.occurrences.len() - answers,
            if answers == 0 {
                String::new()
            } else {
                format!(" and {answers} implementation-defined answer(s)")
            },
            f.entries.len(),
            if f.entries.len() == 1 { "y" } else { "ies" }
        );
        let _ = writeln!(s, "\n<details><summary>occurrences</summary>\n");
        for o in &f.occurrences {
            let _ = writeln!(
                s,
                "- {}{} ({}): {}",
                o.entry
                    .as_deref()
                    .map(|e| format!("`{e}` "))
                    .unwrap_or_default(),
                o.on,
                o.at,
                o.what.replace('|', "\\|")
            );
        }
        let _ = writeln!(s, "\n</details>");
    }
    if !c.unmapped.is_empty() {
        let _ = writeln!(s, "\n## Unmapped failures\n");
        for o in &c.unmapped {
            let _ = writeln!(
                s,
                "- {} {}{} ({}): {}",
                o.source,
                o.on,
                o.entry
                    .as_deref()
                    .map(|e| format!(" `{e}`"))
                    .unwrap_or_default(),
                o.at,
                o.what
            );
        }
    }
    if !c.held.is_empty() {
        let _ = writeln!(
            s,
            "\n## Failures held by candidate findings\n\nNo finding takes these failures; a finding triaged in the candidate lane does, and they count here once it is promoted.\n"
        );
        for (id, occs) in &c.held {
            for o in occs {
                let _ = writeln!(
                    s,
                    "- {id}: {} {}{} ({}): {}",
                    o.source,
                    o.on,
                    o.entry
                        .as_deref()
                        .map(|e| format!(" `{e}`"))
                        .unwrap_or_default(),
                    o.at,
                    o.what
                );
            }
        }
    }
    if !c.input_problems.is_empty() {
        let _ = writeln!(s, "\n## Input problems\n");
        for p in &c.input_problems {
            let _ = writeln!(s, "- {p}");
        }
    }
    let _ = writeln!(
        s,
        "\n## Inputs\n\n| kind | path | sha256 | detail |\n|---|---|---|---|"
    );
    for i in &c.inputs {
        let _ = writeln!(
            s,
            "| {} | `{}` | `{}` | {} |",
            i.kind,
            i.path,
            &i.sha256[..16.min(i.sha256.len())],
            i.detail
        );
    }
    s
}

#[cfg(test)]
mod tests {
    use super::{markdown, root_prefix};
    use crate::collect::Collection;
    use std::path::Path;

    // the headline's covered count is what the findings' own failure occurrences add up to,
    // not the total that also holds the unmapped and the held failures
    #[test]
    fn the_headline_counts_what_the_findings_cover() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../findings/findings.json");
        let c: Collection = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        let covered: usize = c
            .findings
            .iter()
            .flat_map(|f| &f.occurrences)
            .filter(|o| o.source != "answer")
            .count();
        let held: usize = c.held.values().map(Vec::len).sum();
        assert_eq!(covered + held + c.unmapped.len(), c.summary.failures);
        let md = markdown(&c, "../");
        assert!(
            md.contains(&format!(
                "{} failures: {} findings cover {covered}",
                c.summary.failures, c.summary.findings
            )),
            "{md}"
        );
    }

    #[test]
    fn the_prefix_climbs_one_level_per_directory() {
        assert_eq!(root_prefix(Path::new("findings")), "../");
        assert_eq!(root_prefix(Path::new("candidate/findings")), "../../");
        assert_eq!(root_prefix(Path::new("./candidate/findings/")), "../../");
    }
}
