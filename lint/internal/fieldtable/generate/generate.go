// Package generate turns registry/fields.toml into the Go source of package
// fieldtable. It is a library so the fieldtable tests can regenerate the
// table and fail when the committed copy has drifted from the registry.
package generate

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"strings"

	"github.com/BurntSushi/toml"
)

type file struct {
	SchemaVersion int   `toml:"schema_version"`
	Field         []row `toml:"field"`
}

type row struct {
	ID              string   `toml:"id"`
	XDRPath         string   `toml:"xdr_path"`
	ValidatedByCore string   `toml:"validated_by_core"`
	Risk            string   `toml:"risk"`
	Handling        string   `toml:"handling"`
	GoAccessors     []string `toml:"go_accessors"`
}

// Generate parses fields.toml and returns gofmt-ed Go source for package
// fieldtable.
func Generate(src []byte) ([]byte, error) {
	var f file
	if _, err := toml.Decode(string(src), &f); err != nil {
		return nil, fmt.Errorf("parsing fields.toml: %w", err)
	}

	if f.SchemaVersion != 1 {
		return nil, fmt.Errorf("fields.toml schema_version %d, generator understands 1", f.SchemaVersion)
	}

	if err := check(f.Field); err != nil {
		return nil, err
	}

	var b bytes.Buffer

	b.WriteString("// Code generated by lint/internal/fieldtable/gen from registry/fields.toml. DO NOT EDIT.\n\n")
	b.WriteString("package fieldtable\n\n")
	b.WriteString("// Fields is every row of registry/fields.toml, in file order.\n")
	b.WriteString("var Fields = []Field{\n")

	for _, r := range f.Field {
		fmt.Fprintf(&b, "\t{\n\t\tID: %q,\n\t\tXDRPath: %q,\n\t\tValidatedByCore: %q,\n", r.ID, r.XDRPath, r.ValidatedByCore)
		fmt.Fprintf(&b, "\t\tRisk: %q,\n\t\tHandling: %q,\n\t\tAccessors: []Accessor{\n", r.Risk, r.Handling)

		for _, a := range r.GoAccessors {
			parts := strings.Split(a, ".")
			fmt.Fprintf(&b, "\t\t\t{Type: %q, Member: %q},\n", parts[1], parts[2])
		}

		b.WriteString("\t\t},\n\t},\n")
	}

	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated table: %w", err)
	}

	return out, nil
}

func check(rows []row) error {
	var errs []error

	seen := map[string]bool{}

	for i, r := range rows {
		if r.ID == "" {
			errs = append(errs, fmt.Errorf("row %d: empty id", i))
		}

		if seen[r.ID] {
			errs = append(errs, fmt.Errorf("row %s: duplicate id", r.ID))
		}

		seen[r.ID] = true

		switch r.ValidatedByCore {
		case "yes", "partial", "no":
		default:
			errs = append(errs, fmt.Errorf("row %s: validated_by_core %q is not yes, partial or no", r.ID, r.ValidatedByCore))
		}

		for _, a := range r.GoAccessors {
			parts := strings.Split(a, ".")
			if len(parts) != 3 || parts[0] != "xdr" || parts[1] == "" || parts[2] == "" {
				errs = append(errs, fmt.Errorf("row %s: go accessor %q is not of the form xdr.Type.Member", r.ID, a))
			}
		}
	}

	return errors.Join(errs...)
}
