// Package generate turns registry/fields.toml into the Go source of package
// fieldtable, checked against the verdicts measured on core
// (registry/generated/field-verdicts.json, written by shapekit probe compare
// from registry/generated/validation.json). It is a library so the fieldtable
// tests can regenerate the table and fail when the committed copy has drifted
// from either file.
package generate

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"strings"

	"github.com/BurntSushi/toml"
)

type file struct {
	SchemaVersion int   `toml:"schema_version"`
	Field         []row `toml:"field"`
}

type row struct {
	ID              string   `toml:"id"`
	XDRPath         string   `toml:"xdr_path"`
	ValidatedByCore string   `toml:"validated_by_core"`
	Risk            string   `toml:"risk"`
	Handling        string   `toml:"handling"`
	GoAccessors     []string `toml:"go_accessors"`
}

// verdicts is registry/generated/field-verdicts.json: per fields.toml row,
// the verdict measured on core over the struct fields the row speaks about,
// and a reading of core's source where it settles a difference.
type verdicts struct {
	Schema int          `json:"schema"`
	Source string       `json:"source"`
	Rows   []verdictRow `json:"rows"`
}

type verdictRow struct {
	ID       string      `json:"id"`
	Measured string      `json:"measured"`
	Sites    []site      `json:"sites"`
	Settled  *settlement `json:"settled_by_source"`
}

type site struct {
	Field   string `json:"field"`
	Carrier string `json:"carrier"`
	Verdict string `json:"verdict"`
}

type settlement struct {
	Verdict string `json:"verdict"`
	Reading string `json:"reading"`
}

// measuredName is the verdicts file's word for a validated_by_core value.
var measuredName = map[string]string{"yes": "validated", "no": "not-validated", "partial": "mixed"}

// normal reads a settlement's verdict in either vocabulary.
func normal(v string) string {
	if m, ok := measuredName[v]; ok {
		return m
	}

	return v
}

// Generate parses fields.toml and the measured verdicts, checks that every
// row's validated_by_core is what core was measured to do (or what a reading
// of its source settles), and returns gofmt-ed Go source for package
// fieldtable.
func Generate(src, measured []byte) ([]byte, error) {
	var f file
	if _, err := toml.Decode(string(src), &f); err != nil {
		return nil, fmt.Errorf("parsing fields.toml: %w", err)
	}

	if f.SchemaVersion != 1 {
		return nil, fmt.Errorf("fields.toml schema_version %d, generator understands 1", f.SchemaVersion)
	}

	if err := check(f.Field); err != nil {
		return nil, err
	}

	byID, err := readVerdicts(measured)
	if err != nil {
		return nil, err
	}

	if err := agree(f.Field, byID); err != nil {
		return nil, err
	}

	var b bytes.Buffer

	b.WriteString("// Code generated by lint/internal/fieldtable/gen from registry/fields.toml and registry/generated/field-verdicts.json. DO NOT EDIT.\n\n")
	b.WriteString("package fieldtable\n\n")
	b.WriteString("// Fields is every row of registry/fields.toml, in file order.\n")
	b.WriteString("var Fields = []Field{\n")

	for _, r := range f.Field {
		fmt.Fprintf(&b, "\t{\n\t\tID: %q,\n\t\tXDRPath: %q,\n\t\tValidatedByCore: %q,\n", r.ID, r.XDRPath, r.ValidatedByCore)

		v := byID[r.ID]
		fmt.Fprintf(&b, "\t\tMeasured: %q,\n", v.Measured)

		if v.Settled != nil {
			fmt.Fprintf(&b, "\t\tSettledBy: %q,\n", v.Settled.Reading)
		}
		fmt.Fprintf(&b, "\t\tRisk: %q,\n\t\tHandling: %q,\n\t\tAccessors: []Accessor{\n", r.Risk, r.Handling)

		for _, a := range r.GoAccessors {
			parts := strings.Split(a, ".")
			fmt.Fprintf(&b, "\t\t\t{Type: %q, Member: %q},\n", parts[1], parts[2])
		}

		b.WriteString("\t\t},\n\t},\n")
	}

	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated table: %w", err)
	}

	return out, nil
}

func check(rows []row) error {
	var errs []error

	seen := map[string]bool{}

	for i, r := range rows {
		if r.ID == "" {
			errs = append(errs, fmt.Errorf("row %d: empty id", i))
		}

		if seen[r.ID] {
			errs = append(errs, fmt.Errorf("row %s: duplicate id", r.ID))
		}

		seen[r.ID] = true

		switch r.ValidatedByCore {
		case "yes", "partial", "no":
		default:
			errs = append(errs, fmt.Errorf("row %s: validated_by_core %q is not yes, partial or no", r.ID, r.ValidatedByCore))
		}

		for _, a := range r.GoAccessors {
			parts := strings.Split(a, ".")
			if len(parts) != 3 || parts[0] != "xdr" || parts[1] == "" || parts[2] == "" {
				errs = append(errs, fmt.Errorf("row %s: go accessor %q is not of the form xdr.Type.Member", r.ID, a))
			}
		}
	}

	return errors.Join(errs...)
}

func readVerdicts(src []byte) (map[string]verdictRow, error) {
	var v verdicts

	dec := json.NewDecoder(bytes.NewReader(src))
	dec.DisallowUnknownFields()

	if err := dec.Decode(&v); err != nil {
		return nil, fmt.Errorf("parsing field-verdicts.json: %w", err)
	}

	if v.Schema != 1 {
		return nil, fmt.Errorf("field-verdicts.json schema %d, generator understands 1", v.Schema)
	}

	byID := make(map[string]verdictRow, len(v.Rows))

	var errs []error

	for i, r := range v.Rows {
		if i > 0 && v.Rows[i-1].ID >= r.ID {
			errs = append(errs, fmt.Errorf("field-verdicts.json: row %s is not after %s; rows are sorted by id, each once", r.ID, v.Rows[i-1].ID))
		}

		if !isVerdict(r.Measured) {
			errs = append(errs, fmt.Errorf("field-verdicts.json: row %s measured %q is not validated, not-validated or mixed", r.ID, r.Measured))
		}

		if r.Settled != nil && !isVerdict(normal(r.Settled.Verdict)) {
			errs = append(errs, fmt.Errorf("field-verdicts.json: row %s settled verdict %q is not validated, not-validated or mixed", r.ID, r.Settled.Verdict))
		}

		for _, st := range r.Sites {
			if st.Carrier == "" {
				errs = append(errs, fmt.Errorf("field-verdicts.json: row %s site %s has no carrier", r.ID, st.Field))
			}

			if st.Verdict != "validated" && st.Verdict != "not-validated" {
				errs = append(errs, fmt.Errorf("field-verdicts.json: row %s site %s verdict %q is not validated or not-validated", r.ID, st.Field, st.Verdict))
			}
		}

		byID[r.ID] = r
	}

	return byID, errors.Join(errs...)
}

// agree checks every fields.toml row against its measured verdict. A row
// fails when it says something else than was measured and no reading of
// core's source settles it, and when it says something else than the reading
// settles. A row measured both ways over its sites must say partial; one that
// says yes or no fails with the sites listed.
func agree(rows []row, byID map[string]verdictRow) error {
	var errs []error

	seen := map[string]bool{}

	for _, r := range rows {
		seen[r.ID] = true

		v, ok := byID[r.ID]
		if !ok {
			errs = append(errs, fmt.Errorf("row %s: field-verdicts.json has no verdict for it", r.ID))
			continue
		}

		said := measuredName[r.ValidatedByCore]

		switch {
		case v.Settled != nil:
			if said != normal(v.Settled.Verdict) {
				errs = append(errs, fmt.Errorf("row %s: validated_by_core %q, the source reading %s settles %q", r.ID, r.ValidatedByCore, v.Settled.Reading, v.Settled.Verdict))
			}
		case v.Measured == "mixed" && said != "mixed":
			errs = append(errs, fmt.Errorf("row %s: validated_by_core %q, core was measured both ways and no source reading settles it: %s", r.ID, r.ValidatedByCore, sites(v.Sites)))
		case said != v.Measured:
			errs = append(errs, fmt.Errorf("row %s: validated_by_core %q, measured %s on core: %s", r.ID, r.ValidatedByCore, v.Measured, sites(v.Sites)))
		}
	}

	for id := range byID {
		if !seen[id] {
			errs = append(errs, fmt.Errorf("field-verdicts.json has a verdict for %s, which fields.toml does not have", id))
		}
	}

	return errors.Join(errs...)
}

func isVerdict(v string) bool {
	return v == "validated" || v == "not-validated" || v == "mixed"
}

func sites(ss []site) string {
	parts := make([]string, 0, len(ss))

	for _, s := range ss {
		parts = append(parts, s.Field+" ["+s.Carrier+"] "+s.Verdict)
	}

	return strings.Join(parts, "; ")
}
